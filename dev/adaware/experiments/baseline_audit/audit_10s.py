"""Re-score the saved leave-one-episode-out probabilities at boundary tolerances.

The probabilities were generated by 05_train_eval.py and already have its chosen
6-second smoothing. This script does not retrain or tune on the held-out takes.
"""

import json
import argparse
from itertools import product
from pathlib import Path

import numpy as np


ROOT = Path(__file__).resolve().parents[2]
OOF = ROOT / "data" / "model" / "oof"
PARAMS = json.loads((ROOT / "data" / "model" / "metrics.json").read_text())["params"]
GRID = 0.25


def intervals(prob, times, hi, lo, min_duration, merge_gap):
    low = np.flatnonzero(prob >= lo)
    if not len(low):
        return []
    breaks = np.flatnonzero(np.diff(low) > 1)
    starts = np.r_[low[0], low[breaks + 1]]
    ends = np.r_[low[breaks], low[-1]]
    out = []
    for start, end in zip(starts, ends):
        if prob[start : end + 1].max() < hi:
            continue
        a, b = float(times[start] - GRID / 2), float(times[end] + GRID / 2)
        if out and a - out[-1][1] <= merge_gap:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    return [pair for pair in out if pair[1] - pair[0] >= min_duration]


def max_matching(edges):
    # Max-cardinality bipartite matching prevents greedy match order from changing P/R.
    assigned = {}

    def augment(i, seen):
        for j in edges[i]:
            if j in seen:
                continue
            seen.add(j)
            if j not in assigned or augment(assigned[j], seen):
                assigned[j] = i
                return True
        return False

    return sum(augment(i, set()) for i in range(len(edges)))


def matching(pred, gold, tolerance):
    edges = [[j for j, (c, d) in enumerate(gold) if abs(a - c) <= tolerance and abs(b - d) <= tolerance]
             for a, b in pred]
    return max_matching(edges)


def overlap_matching(pred, gold, minimum_iou):
    edges = []
    for a, b in pred:
        neighbors = []
        for j, (c, d) in enumerate(gold):
            overlap = max(0.0, min(b, d) - max(a, c))
            union = max(b, d) - min(a, c)
            if union and overlap / union >= minimum_iou:
                neighbors.append(j)
        edges.append(neighbors)
    return max_matching(edges)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sweep", action="store_true", help="exploratory, optimistically tuned on test predictions")
    args = parser.parse_args()
    rows = []
    for path in sorted(OOF.glob("*.npz")):
        with np.load(path) as data:
            prob, times = data["prob"].copy(), data["times"].copy()
            gold = list(zip(data["gold_starts"].tolist(), data["gold_ends"].tolist()))
        rows.append((path.name, prob, times, gold))
    if not rows:
        raise SystemExit(f"No OOF predictions at {OOF}")
    print(f"{len(rows)} takes, {sum(len(row[3]) for row in rows)} reference intervals")
    chosen = (PARAMS["threshold"], PARAMS["threshold_low"], PARAMS["min_duration"], 6.0)
    predictions = [(name, intervals(prob, times, *chosen), gold) for name, prob, times, gold in rows]
    for tolerance in (5, 10, 20, 30):
        tp = sum(matching(pred, gold, tolerance) for _, pred, gold in predictions)
        n_pred = sum(len(pred) for _, pred, _ in predictions)
        n_gold = sum(len(gold) for _, _, gold in predictions)
        print(f"{tolerance:2d}s: P={tp / n_pred:.4f} R={tp / n_gold:.4f} "
              f"TP={tp} FP={n_pred - tp} FN={n_gold - tp}")
    for iou in (0.1, 0.5):
        tp = sum(overlap_matching(pred, gold, iou) for _, pred, gold in predictions)
        print(f"IoU>={iou:.1f}: {tp}/{n_gold} reference intervals have a distinct overlapping proposal")
    if args.sweep:
        best = None
        n_gold = sum(len(row[3]) for row in rows)
        for params in product((0.5, 0.6, 0.7, 0.8, 0.9), (0.1, 0.2, 0.3, 0.4),
                              (10.0, 20.0, 30.0), (0.0, 6.0)):
            result = [(intervals(prob, times, *params), gold) for _, prob, times, gold in rows]
            count = sum(len(pred) for pred, _ in result)
            tp = sum(matching(pred, gold, 10) for pred, gold in result)
            p, r = tp / count if count else 0.0, tp / n_gold
            f1 = 2 * p * r / (p + r) if p + r else 0.0
            if best is None or f1 > best[0]:
                best = (f1, p, r, tp, count - tp, n_gold - tp, params)
        print("optimistic test-set tuning at 10s: F1, P, R, TP, FP, FN, params =", best)


if __name__ == "__main__":
    main()
